-- Tabla productos_practica (ejecutar en Supabase > SQL Editor)
create table if not exists public.productos_practica (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Nombre" text,
  descripcion text,
  precio bigint,
  unidades bigint,
  descuento float8,
  disponible boolean default true,
  categoria json,
  image_url text
);

-- Como en tu captura, RLS deshabilitado (cualquiera con la anon key puede leer/escribir)
alter table public.productos_practica disable row level security;

